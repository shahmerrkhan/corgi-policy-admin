"use server";
// Broker server actions. Each one calls requireBroker() first, before reading input or
// opening a transaction; a policyholder, signed-out or unlinked session is rejected.
import { redirect } from "next/navigation";
import { requireBroker } from "@/lib/auth/actor";
import { withTx } from "@/lib/db/with-tx";
import { notifyCoverageCorrected } from "@/lib/email/notify";
import { createCustomerCommand } from "@/lib/services/customers";
import { addCoverageCommand } from "@/lib/services/add-coverage";
import { correctCoverageCommand } from "@/lib/services/correct-coverage";
import {
  isUuid,
  parseAddCoverageInput,
  parseCorrectCoverageInput,
  parseCustomerInput,
  parseIssuePolicyInput,
  type AddCoverageField,
  type CorrectCoverageField,
  type CustomerField,
  type FieldErrors,
  type IssuePolicyField,
} from "@/lib/services/inputs";
import { issuePolicyCommand } from "@/lib/services/issue-policy";

export type FormState<K extends string> = {
  errors?: FieldErrors<K>;
  message?: string;
  /** The submitted text, echoed back so the form keeps it after an error. */
  values?: Record<string, string>;
};

function echo(formData: FormData): Record<string, string> {
  const out: Record<string, string> = {};
  for (const [k, v] of formData) if (typeof v === "string" && !k.startsWith("$ACTION")) out[k] = v;
  return out;
}

export type CustomerFormState = FormState<CustomerField>;
export type IssuePolicyFormState = FormState<IssuePolicyField>;
export type AddCoverageFormState = FormState<AddCoverageField>;
export type CorrectCoverageFormState = FormState<CorrectCoverageField> & {
  /** On a stale review: where to start again from the line's current date. */
  restartHref?: string;
};

export async function createCustomer(_prev: CustomerFormState, formData: FormData): Promise<CustomerFormState> {
  const broker = await requireBroker();
  const parsed = parseCustomerInput(Object.fromEntries(formData));
  if (!parsed.ok) return { errors: parsed.errors, values: echo(formData) };

  const result = await withTx((tx) => createCustomerCommand(tx, broker, parsed.value));
  if (!result.ok) return { errors: { email: result.message }, values: echo(formData) };

  redirect(`/broker/policies/new?customerId=${result.value.customerId}`);
}

export async function issuePolicy(_prev: IssuePolicyFormState, formData: FormData): Promise<IssuePolicyFormState> {
  const broker = await requireBroker();
  const parsed = parseIssuePolicyInput(Object.fromEntries(formData));
  if (!parsed.ok) return { errors: parsed.errors, message: "Check the highlighted fields." };

  const result = await withTx((tx) => issuePolicyCommand(tx, broker, parsed.value));
  if (!result.ok) return { message: result.message };

  redirect(`/broker/policies/${result.value.policyId}`);
}

/**
 * Confirm on the add-coverage review page. requestId (generated by the review page) is the
 * new coverage line's id, so a double submit finds the first line and writes nothing.
 */
export async function addCoverage(_prev: AddCoverageFormState, formData: FormData): Promise<AddCoverageFormState> {
  const broker = await requireBroker();
  const policyId = formData.get("policyId");
  const requestId = formData.get("requestId");
  if (!isUuid(policyId) || !isUuid(requestId)) return { message: "This form is out of date. Start again." };
  const parsed = parseAddCoverageInput(Object.fromEntries(formData));
  if (!parsed.ok) return { errors: parsed.errors, message: "Check the highlighted fields." };

  const result = await withTx((tx) => addCoverageCommand(tx, broker, policyId, requestId, parsed.value));
  if (!result.ok) return { message: result.message };

  redirect(`/broker/policies/${result.value.policyId}#entry-${result.value.chargeId}`);
}

/**
 * Confirm on the correct-coverage-date review page. requestId (generated by the review page)
 * is the new event's id, so a double submit finds the first correction and writes nothing.
 */
export async function correctCoverageDate(
  _prev: CorrectCoverageFormState,
  formData: FormData,
): Promise<CorrectCoverageFormState> {
  const broker = await requireBroker();
  const policyId = formData.get("policyId");
  const requestId = formData.get("requestId");
  const coverageLineId = formData.get("coverageLineId");
  const expectedChargeId = formData.get("expectedChargeId");
  if (!isUuid(policyId) || !isUuid(requestId) || !isUuid(coverageLineId) || !isUuid(expectedChargeId)) {
    return { message: "This form is out of date. Start again." };
  }
  const parsed = parseCorrectCoverageInput(Object.fromEntries(formData));
  if (!parsed.ok) return { errors: parsed.errors, message: "Check the highlighted fields." };

  const result = await withTx((tx) =>
    correctCoverageCommand(tx, broker, policyId, requestId, { coverageLineId, expectedChargeId }, parsed.value),
  );
  if (!result.ok) {
    return result.code === "CHARGE_ALREADY_REVERSED"
      ? { message: result.message, restartHref: `/broker/policies/${policyId}/coverage/${coverageLineId}/correct` }
      : { message: result.message };
  }

  // The transaction has committed. Email the customer once (not on a double submit);
  // notifyCoverageCorrected never throws, so the correction always stands.
  if (!result.value.alreadyCorrected) await notifyCoverageCorrected(result.value.eventId);

  redirect(`/broker/policies/${result.value.policyId}#entry-${result.value.newChargeId}`);
}
